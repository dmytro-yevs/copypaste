/// A validation problem at [path], such as `conditions[2].value`.
class RuleProblem {
  const RuleProblem({required this.path, required this.code, this.offset});

  final String path;
  final String code;

  /// Character offset inside a pattern, when known.
  final int? offset;

  static final _indexed = RegExp(r'^(conditions|actions)\[(\d+)\]');

  int? get conditionIndex => _index('conditions');
  int? get actionIndex => _index('actions');

  int? _index(String list) {
    final match = _indexed.firstMatch(path);
    if (match == null || match[1] != list) return null;
    return int.parse(match[2]!);
  }
}

