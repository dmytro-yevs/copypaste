/// Names the editor shows for ids in a rule.
class RuleOptions {
  const RuleOptions({
    this.devices = const [],
    this.sourceApps = const [],
    this.tags = const [],
    this.transforms = const [],
  });

  final List<RuleChoice> devices;
  final List<RuleChoice> sourceApps;
  final List<RuleChoice> tags;
  final List<RuleTransformChoice> transforms;

  String? deviceName(String id) => _label(devices, id);
  String? sourceAppName(String id) => _label(sourceApps, id);
  String? tagName(String id) => _label(tags, id);
  RuleTransformChoice? transform(String id) =>
      transforms.where((choice) => choice.id == id).firstOrNull;

  static String? _label(List<RuleChoice> choices, String id) =>
      choices.where((choice) => choice.id == id).firstOrNull?.label;
}

