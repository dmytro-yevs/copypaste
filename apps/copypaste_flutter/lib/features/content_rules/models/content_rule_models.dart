import 'dart:convert';

/// Limits the runtime enforces on every device; the editor mirrors them so
/// it can explain a refusal before the runtime is asked.
abstract final class RuleLimits {
  static const maxName = 128;
  static const maxConditions = 20;
  static const maxActions = 8;
  static const maxPatternChars = 2000;
  static const previewItems = 1000;
  static const minExpiry = Duration(minutes: 1);
  static const maxExpiry = Duration(days: 90);

  /// Durations offered for "Delete after" (spec 3.3).
  static const expiryChoices = [
    Duration(minutes: 1),
    Duration(minutes: 5),
    Duration(minutes: 15),
    Duration(hours: 1),
    Duration(hours: 8),
    Duration(hours: 24),
    Duration(days: 7),
    Duration(days: 30),
  ];
}

/// A value with a stable snake_case name in the definition JSON.
abstract interface class RuleWireValue {
  String get wire;
}

T? _fromWire<T extends RuleWireValue>(List<T> values, Object? wire) =>
    values.where((value) => value.wire == wire).firstOrNull;

enum RuleMatchMode implements RuleWireValue {
  all('all'),
  any('any');

  const RuleMatchMode(this.wire);
  @override
  final String wire;
}

enum RuleConditionType implements RuleWireValue {
  contentText('content_text'),
  contentType('content_type'),
  detectedKind('detected_kind'),
  sourceApp('source_app'),
  size('size'),
  privacyMarker('privacy_marker'),
  captureOrigin('capture_origin');

  const RuleConditionType(this.wire);
  @override
  final String wire;

  /// Conditions whose value is a set of choices.
  bool get isList =>
      this != RuleConditionType.contentText && this != RuleConditionType.size;
}

