/// Wire names a list condition of [type] may hold; source apps are free.
List<String> ruleChoicesFor(RuleConditionType type) => switch (type) {
  RuleConditionType.contentType => [
    for (final kind in RuleContentKind.values) kind.wire,
  ],
  RuleConditionType.detectedKind => [
    for (final kind in RuleDetectedKind.values) kind.wire,
  ],
  RuleConditionType.privacyMarker => [
    for (final marker in RulePrivacyMarker.values) marker.wire,
  ],
  RuleConditionType.captureOrigin => [
    for (final origin in RuleCaptureOrigin.values) origin.wire,
  ],
  _ => const [],
};

/// One condition. A type this build does not know keeps its raw JSON, is
/// shown read-only and saved back unchanged.
class RuleCondition {
  const RuleCondition({
    required this.type,
    this.negate = false,
    this.textOp = RuleTextOp.contains,
    this.value = '',
    this.caseSensitive = false,
    this.values = const [],
    this.sizeUnit = RuleSizeUnit.characters,
    this.comparison = RuleComparison.greaterThan,
    this.size = 0,
  }) : raw = null;

  const RuleCondition._unknown(Map<String, Object?> this.raw)
    : type = null,
      negate = false,
      textOp = RuleTextOp.contains,
      value = '',
      caseSensitive = false,
      values = const [],
      sizeUnit = RuleSizeUnit.characters,
      comparison = RuleComparison.greaterThan,
      size = 0;

  /// Null for a type from a newer CopyPaste.
  final RuleConditionType? type;
  final bool negate;
  final RuleTextOp textOp;
  final String value;
  final bool caseSensitive;

  /// Wire names of a list condition, or app identities for a source app.
  final List<String> values;
  final RuleSizeUnit sizeUnit;
  final RuleComparison comparison;
  final int size;
  final Map<String, Object?>? raw;

  bool get unknown => type == null;

  /// The raw type name, also for an unknown condition.
  String get typeName => type?.wire ?? '${raw?['type']}';

  factory RuleCondition.fromJson(Map<String, Object?> json) {
    final type = _fromWire(RuleConditionType.values, json['type']);
    if (type == null) return RuleCondition._unknown(json);
    return RuleCondition(
      type: type,
      negate: json['negate'] == true,
      textOp: _fromWire(RuleTextOp.values, json['op']) ?? RuleTextOp.contains,
      value: json['value'] is String ? json['value'] as String : '',
      caseSensitive: json['case_sensitive'] == true,
      values: [
        for (final value in json['any_of'] as List? ?? const [])
          if (value is String) value,
      ],
      sizeUnit:
          _fromWire(RuleSizeUnit.values, json['unit']) ??
          RuleSizeUnit.characters,
      comparison:
          _fromWire(RuleComparison.values, json['op']) ??
          RuleComparison.greaterThan,
      size: json['value'] is int ? json['value'] as int : 0,
    );
  }

  Map<String, Object?> toJson() => switch (type) {
    null => raw!,
    RuleConditionType.contentText => {
      'type': type!.wire,
      'op': textOp.wire,
      'value': value,
      'case_sensitive': caseSensitive,
      'negate': negate,
    },
    RuleConditionType.size => {
      'type': type!.wire,
      'unit': sizeUnit.wire,
      'op': comparison.wire,
      'value': size,
      'negate': negate,
    },
    _ => {'type': type!.wire, 'any_of': values, 'negate': negate},
  };

  RuleCondition copyWith({
    RuleConditionType? type,
    bool? negate,
    RuleTextOp? textOp,
    String? value,
    bool? caseSensitive,
    List<String>? values,
    RuleSizeUnit? sizeUnit,
    RuleComparison? comparison,
    int? size,
  }) {
    if (unknown) return this;
    final changedType = type != null && type != this.type;
    return RuleCondition(
      type: type ?? this.type!,
      negate: negate ?? this.negate,
      textOp: textOp ?? this.textOp,
      value: value ?? this.value,
      caseSensitive: caseSensitive ?? this.caseSensitive,
      values: values ?? (changedType ? const [] : this.values),
      sizeUnit: sizeUnit ?? this.sizeUnit,
      comparison: comparison ?? this.comparison,
      size: size ?? this.size,
    );
  }
}

enum RuleActionType implements RuleWireValue {
  dontSave('dont_save'),
  markSecret('mark_secret'),
  hideFromAi('hide_from_ai'),
  deleteAfter('delete_after'),
  addTags('add_tags'),
  transform('transform');

  const RuleActionType(this.wire);
  @override
  final String wire;
}

/// Why an action cannot join a rule's actions (content-rules R-7).
enum RuleActionBlock {
  /// "Don't save" must be the rule's only action.
  dontSaveAlone,

  /// The rule already has this action.
  present,

  /// The rule already has the most actions it may hold.
  full,
}

class RuleAction {
  const RuleAction({
    required this.type,
    this.clearClipboardAfterSecs,
    this.expiry = const Duration(minutes: 15),
    this.clearClipboard = false,
    this.tagIds = const [],
    this.transformId = '',
    this.params = const {},
    this.replaceClipboard = false,
  }) : raw = null;

  const RuleAction._unknown(Map<String, Object?> this.raw)
    : type = null,
      clearClipboardAfterSecs = null,
      expiry = Duration.zero,
      clearClipboard = false,
      tagIds = const [],
      transformId = '',
      params = const {},
      replaceClipboard = false;

  final RuleActionType? type;
  final int? clearClipboardAfterSecs;
  final Duration expiry;
  final bool clearClipboard;
  final List<String> tagIds;
  final String transformId;
  final Map<String, Object?> params;
  final bool replaceClipboard;
  final Map<String, Object?>? raw;

  bool get unknown => type == null;
  String get typeName => type?.wire ?? '${raw?['type']}';

  factory RuleAction.fromJson(Map<String, Object?> json) {
    final type = _fromWire(RuleActionType.values, json['type']);
    if (type == null) return RuleAction._unknown(json);
    return RuleAction(
      type: type,
      clearClipboardAfterSecs: json['clear_clipboard_after_secs'] as int?,
      expiry: Duration(milliseconds: json['duration_ms'] as int? ?? 900000),
      clearClipboard: json['clear_clipboard'] == true,
      tagIds: [
        for (final id in json['tag_ids'] as List? ?? const [])
          if (id is String) id,
      ],
      transformId: json['transform_id'] as String? ?? '',
      params: Map<String, Object?>.from(json['params'] as Map? ?? const {}),
      replaceClipboard: json['replace_clipboard'] == true,
    );
  }

  Map<String, Object?> toJson() => switch (type) {
    null => raw!,
    RuleActionType.dontSave => {
      'type': type!.wire,
      'clear_clipboard_after_secs': ?clearClipboardAfterSecs,
    },
    RuleActionType.markSecret ||
    RuleActionType.hideFromAi => {'type': type!.wire},
    RuleActionType.deleteAfter => {
      'type': type!.wire,
      'duration_ms': expiry.inMilliseconds,
      'clear_clipboard': clearClipboard,
    },
    RuleActionType.addTags => {'type': type!.wire, 'tag_ids': tagIds},
    RuleActionType.transform => {
      'type': type!.wire,
      'transform_id': transformId,
      if (params.isNotEmpty) 'params': params,
      'replace_clipboard': replaceClipboard,
    },
  };

  RuleAction copyWith({
    Duration? expiry,
    bool? clearClipboard,
    List<String>? tagIds,
    String? transformId,
    bool? replaceClipboard,
  }) => unknown
      ? this
      : RuleAction(
          type: type,
          clearClipboardAfterSecs: clearClipboardAfterSecs,
          expiry: expiry ?? this.expiry,
          clearClipboard: clearClipboard ?? this.clearClipboard,
          tagIds: tagIds ?? this.tagIds,
          transformId: transformId ?? this.transformId,
          params: transformId == null || transformId == this.transformId
              ? params
              : const {},
          replaceClipboard: replaceClipboard ?? this.replaceClipboard,
        );
}

/// Match mode, conditions, actions and the stop flag: one atomic value that
/// syncs as JSON (schema version 1).
class RuleDefinition {
  const RuleDefinition({
    this.matchMode = RuleMatchMode.all,
    this.conditions = const [],
    this.actions = const [],
    this.stopProcessing = false,
  });

  final RuleMatchMode matchMode;
  final List<RuleCondition> conditions;
  final List<RuleAction> actions;
  final bool stopProcessing;

  /// Throws [FormatException] when [source] is not a definition object.
  factory RuleDefinition.parse(String source) {
    final json = jsonDecode(source);
    if (json is! Map<String, Object?>) {
      throw const FormatException('A rule definition is a JSON object.');
    }
    return RuleDefinition(
      matchMode:
          _fromWire(RuleMatchMode.values, json['match']) ?? RuleMatchMode.all,
      conditions: [
        for (final condition in json['conditions'] as List? ?? const [])
          RuleCondition.fromJson(Map<String, Object?>.from(condition as Map)),
      ],
      actions: [
        for (final action in json['actions'] as List? ?? const [])
          RuleAction.fromJson(Map<String, Object?>.from(action as Map)),
      ],
      stopProcessing: json['stop_processing'] == true,
    );
  }

  String toJson() => jsonEncode({
    'match': matchMode.wire,
    'conditions': [for (final condition in conditions) condition.toJson()],
    'actions': [for (final action in actions) action.toJson()],
    'stop_processing': stopProcessing,
  });

  /// A rule with no conditions applies to every copy (R-1).
  bool get matchesEverything => conditions.isEmpty;

  bool get needsNewerVersion =>
      conditions.any((condition) => condition.unknown) ||
      actions.any((action) => action.unknown);

  bool has(RuleActionType type) => actions.any((action) => action.type == type);

  /// Why [type] cannot be added, or null when it can.
  RuleActionBlock? blockFor(RuleActionType type) {
    if (has(type)) return RuleActionBlock.present;
    if (actions.length >= RuleLimits.maxActions) return RuleActionBlock.full;
    if (has(RuleActionType.dontSave) ||
        (type == RuleActionType.dontSave && actions.isNotEmpty)) {
      return RuleActionBlock.dontSaveAlone;
    }
    return null;
  }

  RuleDefinition copyWith({
    RuleMatchMode? matchMode,
    List<RuleCondition>? conditions,
    List<RuleAction>? actions,
    bool? stopProcessing,
  }) => RuleDefinition(
    matchMode: matchMode ?? this.matchMode,
    conditions: conditions ?? this.conditions,
    actions: actions ?? this.actions,
    stopProcessing: stopProcessing ?? this.stopProcessing,
  );
}

/// One rule as listed. [deviceIds] empty means every device.
class ContentRule {
  const ContentRule({
    required this.id,
    required this.name,
    required this.definitionJson,
    this.builtin = false,
    this.enabled = true,
    this.orderKey = '',
    this.deviceIds = const [],
    this.errorCode,
    this.newFromDevice,
    this.unsupported = false,
    this.deletedAt,
    this.matchCount = 0,
    this.lastMatchedAt,
  });

  final String id;
  final String name;
  final String definitionJson;
  final bool builtin;
  final bool enabled;
  final String orderKey;
  final List<String> deviceIds;

  /// A validation code when the rule cannot run here; captures it could
  /// match are stored as secret and hidden from AI meanwhile (R-20).
  final String? errorCode;

  /// The device that wrote this rule within the last 7 days.
  final String? newFromDevice;

  /// Written by a newer CopyPaste; it does not run here.
  final bool unsupported;
  final DateTime? deletedAt;
  final int matchCount;
  final DateTime? lastMatchedAt;

  bool get deleted => deletedAt != null;

  /// Null when the stored JSON cannot be read by this build.
  RuleDefinition? get definition {
    try {
      return RuleDefinition.parse(definitionJson);
    } on Object {
      return null;
    }
  }
}

