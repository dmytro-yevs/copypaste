/// How rules treat a sample or a stored clip, and the combined result.
class RuleTrace {
  const RuleTrace({
    this.steps = const [],
    this.skipped = false,
    this.secret = false,
    this.hiddenFromAi = false,
    this.expiresAfter,
    this.tagIds = const [],
    this.transformIds = const [],
  });

  final List<RuleTraceStep> steps;
  final bool skipped;
  final bool secret;
  final bool hiddenFromAi;
  final Duration? expiresAfter;
  final List<String> tagIds;
  final List<String> transformIds;

  bool get noEffect =>
      !skipped &&
      !secret &&
      !hiddenFromAi &&
      expiresAfter == null &&
      tagIds.isEmpty &&
      transformIds.isEmpty;
}

