#!/usr/bin/env python3
"""Generate src/strings_table.rs from the module's ARB translations.

The module shows the same snippet strings the app used before snippets
became a module. Each ARB message becomes one table row per locale string,
in the order of LOCALES. A message that is a whole ICU `plural` or `select`
becomes one row per variant, keyed `key#variant` (`=0`, `=1`, `one`, `few`,
`many`, `other`, or the select option); `src/strings.rs` picks the variant.
A locale missing a message falls back to English, and one missing a
variant to its own `other`.

Run from anywhere: python3 modules/snippets/scripts/generate-strings.py
"""

import json
import pathlib
import re
import sys

LOCALES = ["en", "de", "es", "fr", "it", "ja", "ko", "pl", "pt", "ru", "tr", "uk", "zh"]
PREFIXES = ("snippets",)
EXTRA_KEYS = (
    "settingsSectionSnippets",
    "trayNewSnippet",
    "historyActionSaveAsSnippet",
    "commonCancel",
    "commonSave",
    "commonDelete",
    "commonDone",
    "commonBack",
    "commonContinue",
)

ROOT = pathlib.Path(__file__).resolve().parents[3]
# A snapshot of the app translations taken when snippets left the app.
ARB_DIR = ROOT / "modules" / "snippets" / "l10n"
OUTPUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "strings_table.rs"
ICU = re.compile(r"^\{(\w+), (plural|select),")


def matching_brace(text, start):
    depth = 0
    for index in range(start, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return index
    raise ValueError(f"unbalanced braces in {text!r}")


def variants(message):
    """`{"": message}` for plain text, else the variants of a whole ICU message."""
    found = ICU.match(message)
    if not found or matching_brace(message, 0) != len(message) - 1:
        return {"": message}
    body = message[found.end() : -1]
    result = {}
    at = 0
    while at < len(body):
        if body[at].isspace():
            at += 1
            continue
        open_at = body.index("{", at)
        name = body[at:open_at].strip()
        close_at = matching_brace(body, open_at)
        result[name] = body[open_at + 1 : close_at]
        at = close_at + 1
    return result


def rust_string(text):
    out = ['"']
    for char in text:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif ord(char) < 0x20:
            out.append(f"\\u{{{ord(char):x}}}")
        else:
            out.append(char)
    out.append('"')
    return "".join(out)


def main():
    arbs = {
        locale: json.loads((ARB_DIR / f"app_{locale}.arb").read_text(encoding="utf-8"))
        for locale in LOCALES
    }
    english = arbs["en"]
    keys = sorted(
        key
        for key in english
        if not key.startswith("@") and (key.startswith(PREFIXES) or key in EXTRA_KEYS)
    )
    missing = [key for key in EXTRA_KEYS if key not in english]
    if missing:
        sys.exit(f"missing English keys: {missing}")
    rows = {}
    for key in keys:
        base = variants(english[key])
        localized = {
            locale: variants(arbs[locale].get(key, english[key])) for locale in LOCALES
        }
        names = list(base)
        for locale in LOCALES:
            names += [name for name in localized[locale] if name not in names]
        for name in names:
            row_key = key if name == "" else f"{key}#{name}"
            rows[row_key] = [
                localized[locale].get(
                    name, localized[locale].get("other", base.get(name, base.get("other", "")))
                )
                for locale in LOCALES
            ]

    lines = [
        "//! Generated by `scripts/generate-strings.py` from `l10n/`, a snapshot of the app's translations.",
        "//! Do not edit by hand; run the script again instead.",
        "",
        f"pub(crate) const LOCALES: [&str; {len(LOCALES)}] = [",
        "    " + ", ".join(f'"{locale}"' for locale in LOCALES) + ",",
        "];",
        "",
        "/// Sorted by key. Variants of ICU plural and select messages are",
        "/// `key#variant`.",
        f"pub(crate) const TABLE: &[(&str, [&str; {len(LOCALES)}])] = &[",
    ]
    for row_key in sorted(rows):
        lines.append(f"    ({rust_string(row_key)}, [")
        lines.extend(f"        {rust_string(text)}," for text in rows[row_key])
        lines.append("    ]),")
    lines.append("];")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} rows from {len(keys)} keys written to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
