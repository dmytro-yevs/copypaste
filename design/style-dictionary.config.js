const sources = (theme) => [
  `tokens/color/theme.${theme}.json`,
  `tokens/color/accents.${theme}.json`,
  `tokens/color/static.json`,
  `tokens/elevation.${theme}.json`,
  'tokens/elevation.static.json',
  'tokens/typography.json',
  'tokens/spacing.json',
  'tokens/radius.json',
  'tokens/motion.json',
  'tokens/size.json',
  'tokens/layout.json',
  'tokens/z-index.json',
  'tokens/translucency.json',
  'tokens/semantic/tailwind.json',
  'tokens/semantic/material.json',
];

const CSS_TRANSFORMS = [
  'name/copypaste',
  'shadow/css/shorthand',
  'fontFamily/css',
  'cubicBezier/css',
];

/**
 * No colour transform on the CSS side on purpose: the token values are already
 * exactly the CSS §8 specifies, including the rgba() state layers and the
 * color-mix() selection fill, and round-tripping them through a colour parser
 * would only introduce drift.
 */
const cssPlatform = (theme, files) => ({
  transforms: CSS_TRANSFORMS,
  buildPath: DIST,
  files,
});

const composePlatform = (files) => ({
  transforms: ['name/copypaste', 'color/composeColor'],
  buildPath: DIST,
  files,
});

const themeConfig = (theme) => ({
  source: sources(theme),
  log: { verbosity: 'silent', warnings: 'warn' },
  platforms: {
    css: cssPlatform(theme, cssFiles(theme)),
    compose: composePlatform(theme === 'dark' ? composeFiles() : []),
    ...(theme === 'dark' ? { tailwind: cssPlatform(theme, [tailwindFile()]) } : {}),
  },
});

const themeSelectors = (theme) =>
  theme === 'dark'
    ? [':root', ':root[data-theme="dark"]', '.theme-scope[data-theme="dark"]']
    : [':root[data-theme="light"]', '.theme-scope[data-theme="light"]'];

const accentSelectors = (theme) =>
  theme === 'dark'
    ? [':root[data-accent="%s"]', '.theme-scope[data-accent="%s"]']
    : [
        ':root[data-theme="light"][data-accent="%s"]',
        '.theme-scope[data-theme="light"][data-accent="%s"]',
      ];

function cssFiles(theme) {
  const files = [
    {
      destination: `css/tokens.${theme}.css`,
      format: 'css/copypaste',
      filter: (t) => isThemed(t) && inGroup(t, 'color', 'elevation') && targets(t).includes('css'),
      options: {
        title: `CopyPaste ${theme} theme — port-manifest §8.${theme === 'dark' ? 1 : 2}, §8.3.`,
        selectors: themeSelectors(theme),
        prelude: `color-scheme: ${theme};`,
      },
    },
    {
      destination: `css/accents.${theme}.css`,
      format: 'css/copypaste-accents',
      filter: (t) => inGroup(t, 'accents'),
      options: {
        title: `CopyPaste accent axis, ${theme} — port-manifest §8.4.`,
        selectors: accentSelectors(theme),
      },
    },
  ];
  if (theme !== 'dark') return files;
  return [
    {
      destination: 'css/tokens.base.css',
      format: 'css/copypaste',
      filter: (t) =>
        !isThemed(t) && !inGroup(t, 'tw', 'm3', 'accents') && targets(t).includes('css'),
      options: {
        title: 'CopyPaste theme-independent tokens — port-manifest §8.5, §8.6.',
        selectors: [':root'],
      },
    },
    ...files,
    {
      destination: 'css/index.css',
      format: 'css/copypaste-index',
      // The format emits imports, not tokens; the filter only has to be non-empty
      // so Style Dictionary writes the file.
      filter: (t) => inGroup(t, 'z'),
      options: {
        title: 'CopyPaste design tokens — entry point.',
        imports: [
          'tokens.base.css',
          'tokens.dark.css',
          'tokens.light.css',
          'accents.dark.css',
          'accents.light.css',
          'theme.css',
        ],
      },
    },
  ];
}

const tailwindFile = () => ({
  destination: 'css/theme.css',
  format: 'css/copypaste-tailwind',
  filter: (t) => !inGroup(t, 'm3'),
  options: { title: 'CopyPaste Tailwind v4 theme layer — the shadcn/ui semantic contract.' },
});

const composeFiles = () => [
  {
    destination: 'compose/Color.kt',
    format: 'compose/copypaste-colors',
    filter: (t) => inGroup(t, 'color', 'accents'),
    options: { title: 'CopyPaste colours for Jetpack Compose.' },
  },
  {
    destination: 'compose/ColorScheme.kt',
    format: 'compose/copypaste-colorscheme',
    filter: (t) => inGroup(t, 'm3'),
    options: { title: 'CopyPaste Material 3 ColorSchemes.' },
  },
  {
    destination: 'compose/Dimens.kt',
    format: 'compose/copypaste-dimens',
    filter: (t) => inGroup(t, 'space', 'radius', 'size', 'layout', 'type', 'motion', 'z'),
    options: { title: 'CopyPaste spacing, radii, sizes, type and motion for Compose.' },
  },
];

/* ------------------------------------------------------------------- build */

const dark = new StyleDictionary(themeConfig('dark'));
const light = new StyleDictionary(themeConfig('light'));
await Promise.all([dark.hasInitialized, light.hasInitialized]);

compose.dark = await dark.getPlatformTokens('compose');
compose.light = await light.getPlatformTokens('compose');

await dark.buildAllPlatforms();
await light.buildPlatform('css');

await mkdir(`${DIST}compose`, { recursive: true });
await writeFile(
  `${DIST}README.txt`,
  'Everything in this directory is generated from design/tokens/ by Style Dictionary.\n' +
    'Do not edit it. Run `npm run build` in design/ instead.\n',
);

console.log(
  `built ${compose.dark.allTokens.length} dark and ` +
    `${compose.light.allTokens.length} light resolved tokens -> ${DIST}`,
);
