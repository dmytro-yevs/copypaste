//! The rule definition schema (version 1).
//!
//! A definition is declarative data only: match mode, conditions, actions and
//! the stop-processing flag, stored as one atomic JSON object. Condition and
//! action types this build does not know are kept as raw values, so a rule
//! written by a newer version is recognised as such and never evaluated
//! partially.

use serde::{Deserialize, Deserializer, Serialize, Serializer};
use serde_json::{Map, Value};

/// The newest definition schema this build evaluates.
pub const SCHEMA_VERSION: u32 = 1;
/// Rules evaluated per device; rules past the cap fail closed.
pub const MAX_RULES: usize = 200;
pub const MAX_CONDITIONS: usize = 20;
pub const MAX_ACTIONS: usize = 8;
/// Characters in one text value or regex pattern.
pub const MAX_PATTERN_CHARS: usize = 2_000;
pub const MAX_LIST_VALUES: usize = 64;
pub const MAX_TAGS_PER_ACTION: usize = 32;
pub const MIN_EXPIRY_MS: i64 = 60_000;
pub const MAX_EXPIRY_MS: i64 = 90 * 24 * 60 * 60 * 1_000;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MatchMode {
    All,
    Any,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RuleDefinition {
    #[serde(rename = "match")]
    pub match_mode: MatchMode,
    #[serde(default)]
    pub conditions: Vec<ConditionSlot>,
    pub actions: Vec<ActionSlot>,
    #[serde(default)]
    pub stop_processing: bool,
}

impl RuleDefinition {
    pub fn parse(json: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(json)
    }

    #[must_use]
    pub fn to_json(&self) -> String {
        serde_json::to_string(self).expect("rule definitions serialize")
    }

    /// True when a condition or action type is unknown to this build.
    #[must_use]
    pub fn needs_newer_version(&self) -> bool {
        self.conditions
            .iter()
            .any(|slot| matches!(slot, ConditionSlot::Unknown(_)))
            || self
                .actions
                .iter()
                .any(|slot| matches!(slot, ActionSlot::Unknown(_)))
    }

    pub fn known_actions(&self) -> impl Iterator<Item = &Action> {
        self.actions.iter().filter_map(|slot| match slot {
            ActionSlot::Known(action) => Some(action),
            ActionSlot::Unknown(_) => None,
        })
    }
}

