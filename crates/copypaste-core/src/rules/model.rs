pub use super::detect::DetectedKind;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum Condition {
    ContentText {
        op: TextOp,
        value: String,
        #[serde(default)]
        case_sensitive: bool,
        #[serde(default)]
        negate: bool,
    },
    ContentType {
        any_of: Vec<ContentTypeKind>,
        #[serde(default)]
        negate: bool,
    },
    DetectedKind {
        any_of: Vec<DetectedKind>,
        #[serde(default)]
        negate: bool,
    },
    /// Stable app identities: bundle id, executable identity or package name.
    SourceApp {
        any_of: Vec<String>,
        #[serde(default)]
        negate: bool,
    },
    Size {
        unit: SizeUnit,
        op: Comparison,
        value: u64,
        #[serde(default)]
        negate: bool,
    },
    PrivacyMarker {
        any_of: Vec<PrivacyMarker>,
        #[serde(default)]
        negate: bool,
    },
    CaptureOrigin {
        any_of: Vec<CaptureOrigin>,
        #[serde(default)]
        negate: bool,
    },
}

impl Condition {
    const TYPES: [&'static str; 7] = [
        "content_text",
        "content_type",
        "detected_kind",
        "source_app",
        "size",
        "privacy_marker",
        "capture_origin",
    ];

    #[must_use]
    pub fn negated(&self) -> bool {
        match self {
            Self::ContentText { negate, .. }
            | Self::ContentType { negate, .. }
            | Self::DetectedKind { negate, .. }
            | Self::SourceApp { negate, .. }
            | Self::Size { negate, .. }
            | Self::PrivacyMarker { negate, .. }
            | Self::CaptureOrigin { negate, .. } => *negate,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum Action {
    /// Terminal: the capture is never persisted.
    DontSave {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        clear_clipboard_after_secs: Option<u32>,
    },
    MarkSecret {},
    HideFromIntegrations {},
    DeleteAfter {
        duration_ms: i64,
        #[serde(default)]
        clear_clipboard: bool,
    },
    AddTags {
        tag_ids: Vec<String>,
    },
    /// Executed by the runtime; core only carries the id and parameters.
    Transform {
        transform_id: String,
        #[serde(default, skip_serializing_if = "Map::is_empty")]
        params: Map<String, Value>,
        #[serde(default)]
        replace_clipboard: bool,
    },
}

impl Action {
    const TYPES: [&'static str; 6] = [
        "dont_save",
        "mark_secret",
        "hide_from_integrations",
        "delete_after",
        "add_tags",
        "transform",
    ];

    /// Actions that only add protection and may run on received items.
    #[must_use]
    pub const fn is_protective(&self) -> bool {
        matches!(
            self,
            Self::DontSave { .. }
                | Self::MarkSecret {}
                | Self::HideFromIntegrations {}
                | Self::DeleteAfter { .. }
        )
    }

    #[must_use]
    pub const fn type_name(&self) -> &'static str {
        match self {
            Self::DontSave { .. } => "dont_save",
            Self::MarkSecret {} => "mark_secret",
            Self::HideFromIntegrations {} => "hide_from_integrations",
            Self::DeleteAfter { .. } => "delete_after",
            Self::AddTags { .. } => "add_tags",
            Self::Transform { .. } => "transform",
        }
    }
}

/// A condition this build understands, or the raw value of one it does not.
#[derive(Debug, Clone, PartialEq)]
pub enum ConditionSlot {
    Known(Condition),
    Unknown(Value),
}

#[derive(Debug, Clone, PartialEq)]
pub enum ActionSlot {
    Known(Action),
    Unknown(Value),
}

/// Dispatches on `type` so a malformed known entry stays an error while an
/// unknown type is preserved.
fn slot<'de, D, T>(deserializer: D, types: &[&str]) -> Result<Result<T, Value>, D::Error>
where
    D: Deserializer<'de>,
    T: serde::de::DeserializeOwned,
{
    let value = Value::deserialize(deserializer)?;
    let Some(kind) = value.get("type").and_then(Value::as_str) else {
        return Err(serde::de::Error::missing_field("type"));
    };
    if types.contains(&kind) {
        serde_json::from_value(value)
            .map(Ok)
            .map_err(serde::de::Error::custom)
    } else {
        Ok(Err(value))
    }
}

impl<'de> Deserialize<'de> for ConditionSlot {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Ok(match slot(deserializer, &Condition::TYPES)? {
            Ok(condition) => Self::Known(condition),
            Err(raw) => Self::Unknown(raw),
        })
    }
}

impl Serialize for ConditionSlot {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        match self {
            Self::Known(condition) => condition.serialize(serializer),
            Self::Unknown(raw) => raw.serialize(serializer),
        }
    }
}

impl<'de> Deserialize<'de> for ActionSlot {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Ok(match slot(deserializer, &Action::TYPES)? {
            Ok(action) => Self::Known(action),
            Err(raw) => Self::Unknown(raw),
        })
    }
}

impl Serialize for ActionSlot {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        match self {
            Self::Known(action) => action.serialize(serializer),
            Self::Unknown(raw) => raw.serialize(serializer),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips_known_and_preserves_unknown_types() {
        let json = r#"{"match":"any","conditions":[
            {"type":"content_text","op":"contains","value":"x"},
            {"type":"window_title","op":"contains","value":"y"}],
            "actions":[{"type":"mark_secret"},{"type":"pin"}]}"#;
        let definition = RuleDefinition::parse(json).unwrap();
        assert!(definition.needs_newer_version());
        assert!(matches!(
            definition.conditions[1],
            ConditionSlot::Unknown(_)
        ));
        let again = RuleDefinition::parse(&definition.to_json()).unwrap();
        assert_eq!(again, definition);
    }

    #[test]
    fn malformed_known_types_and_unknown_fields_are_errors() {
        for json in [
            r#"{"match":"all","conditions":[{"type":"size","unit":"bytes"}],"actions":[]}"#,
            r#"{"match":"all","conditions":[{"type":"content_text","op":"contains","value":"x","extra":1}],"actions":[]}"#,
            r#"{"match":"all","actions":[{"type":"mark_secret","extra":true}]}"#,
            r#"{"match":"all","actions":[],"later":true}"#,
        ] {
            assert!(RuleDefinition::parse(json).is_err(), "{json}");
        }
    }
}
