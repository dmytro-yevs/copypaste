import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { RESPONSIVE_POSTCSS_VARIABLES as value } from "../src/lib/layoutBreakpoints.ts";

const output = `/* Generated by scripts/generate-responsive-media.mjs. */
@custom-media --cp-xs (max-width: ${value.cpXs});
@custom-media --cp-sm (max-width: ${value.cpSm});
@custom-media --cp-failure (max-width: ${value.cpFailure});
@custom-media --cp-md (max-width: ${value.cpMd});
@custom-media --cp-toolbar (max-width: ${value.cpToolbar});
@custom-media --cp-lg (min-width: ${value.cpLg});
@custom-media --cp-wide (min-width: ${value.cpWide});
@custom-media --cp-roster (min-width: ${value.cpRoster});
@custom-media --cp-roster-wide (min-width: ${value.cpRosterWide});
@custom-media --cp-short (max-height: ${value.cpShort});
@custom-media --cp-short-mobile (max-height: ${value.cpShortMobile});
@custom-media --cp-inspector-short (max-height: ${value.cpInspectorShort});
@custom-media --cp-lg-short (min-width: ${value.cpLg}) and (max-height: ${value.cpShort});
@custom-media --cp-sm-short-mobile (max-width: ${value.cpSm}) and (max-height: ${value.cpShortMobile});
`;

const outputPath = fileURLToPath(
  new URL("../src/styles/media.css", import.meta.url),
);
const mode = process.argv[2];

if (mode === "--check") {
  if (readFileSync(outputPath, "utf8") !== output) {
    console.error("responsive media is stale; run npm run generate:responsive");
    process.exitCode = 1;
  }
} else if (mode === undefined) {
  writeFileSync(outputPath, output);
} else {
  console.error("usage: node scripts/generate-responsive-media.mjs [--check]");
  process.exitCode = 2;
}
